import { fmtUsd, fmtNum } from "./render.js";

/**
 * Turn a report into a paste-ready CLAUDE.md block.
 * Rules are phrased as instructions to the agent, backed by the numbers that justify them.
 */
export function advise(report, { max = 8, days } = {}) {
  const lines = [];
  const rules = [];

  // 1. Files / calls repeated across sessions.
  const rep = new Map();
  for (const f of report.waste) {
    if (f.kind !== "repeat") continue;
    const g = rep.get(f.detail) || { tool: f.tool, detail: f.detail, count: 0, usd: 0, sessions: 0 };
    g.count += f.count;
    g.usd += f.usd || 0;
    g.sessions++;
    rep.set(f.detail, g);
  }
  for (const g of [...rep.values()].sort((a, b) => b.usd - a.usd).slice(0, 4)) {
    const what =
      g.tool === "Read" ? `Before reading \`${g.detail}\``
      : g.tool === "Glob" || g.tool === "Grep" ? `Before searching \`${g.detail}\` again`
      : g.tool === "Bash" ? `Before running \`${g.detail}\``
      : `Before calling \`${g.tool}\` with \`${g.detail}\``;
    rules.push({ usd: g.usd, text: `${what}, check whether the result is already in context. It was repeated ${g.count} times in ${g.sessions} session${g.sessions > 1 ? "s" : ""} (~${fmtUsd(g.usd)} of context cost).` });
  }

  // 2. Large outputs.
  const big = new Map();
  for (const f of report.waste) {
    if (f.kind !== "large-output") continue;
    const k = `${f.tool} ${f.detail}`;
    const g = big.get(k) || { tool: f.tool, detail: f.detail, n: 0, maxChars: 0, usd: 0 };
    g.n++;
    g.usd += f.usd || 0;
    g.maxChars = Math.max(g.maxChars, f.chars);
    big.set(k, g);
  }
  for (const g of [...big.values()].sort((a, b) => b.usd - a.usd).slice(0, 3)) {
    const fix = g.tool === "Bash" ? "pipe it through `head`, `tail` or `grep`" : g.tool === "Read" ? "use `offset`/`limit` to read only the part you need" : "narrow the query";
    rules.push({ usd: g.usd, text: `\`${g.detail}\` returned up to ${fmtNum(g.maxChars)} characters in one call (${g.n}×, ~${fmtUsd(g.usd)}); ${fix}.` });
  }

  // 3. Retries.
  const retry = new Map();
  for (const f of report.waste) {
    if (f.kind !== "retry") continue;
    const g = retry.get(f.detail) || { detail: f.detail, n: 0, usd: 0 };
    g.n += f.count;
    g.usd += f.usd || 0;
    retry.set(f.detail, g);
  }
  for (const g of [...retry.values()].sort((a, b) => b.n - a.n).slice(0, 2)) {
    rules.push({ usd: g.usd, text: `When \`${g.detail}\` fails, change something before running it again; it was retried unchanged ${g.n} time${g.n > 1 ? "s" : ""}.` });
  }

  // 4. Error-prone tools (global, not per session).
  for (const t of report.byTool) {
    if (t.calls < 10 || t.errors / t.calls < 0.25) continue;
    rules.push({ usd: 0, text: `\`${t.key}\` fails ${Math.round((t.errors / t.calls) * 100)}% of the time (${t.errors}/${t.calls}). Fix its setup or stop calling it.` });
  }

  // 5. Cold cache.
  const cold = report.waste.filter((f) => f.kind === "cold-cache");
  if (cold.length) rules.push({ usd: 0, text: `${cold.length} long session${cold.length > 1 ? "s" : ""} ran with a cache hit rate under 50%. Avoid leaving a session idle for more than an hour; start a fresh one instead.` });

  rules.sort((a, b) => b.usd - a.usd);
  const scope = days ? `last ${days} days` : "all sessions";
  lines.push(`## Token hygiene (generated by ccledger, ${new Date().toISOString().slice(0, 10)}, ${scope})`);
  lines.push("");
  if (!rules.length) lines.push("- No recurring waste patterns found. Nice.");
  for (const r of rules.slice(0, max)) lines.push(`- ${r.text}`);
  lines.push("");
  const ctx = report.totals.ctxCost;
  lines.push(`<!-- ${fmtNum(report.totals.toolCalls)} tool calls, ~${fmtUsd(ctx)} of estimated context cost from tool results; top tools by context cost: ${report.byTool.slice().sort((a, b) => b.ctxCost - a.ctxCost).slice(0, 3).map((t) => `${t.key} ${fmtUsd(t.ctxCost)}`).join(", ")} -->`);
  return lines.join("\n");
}
